import assert from "node:assert/strict";
import { compileGlob, prepareRecords } from "./algolia-records.mjs";
assert.ok(compileGlob("docs/**/*.md").test("docs/a.md"));
assert.ok(compileGlob("docs/**/*.md").test("docs/nested/deep/a.md"));
assert.equal(compileGlob("docs/*.md").test("docs/nested/a.md"), false);
assert.ok(compileGlob("/docs/_pages/*.*").test("docs/_pages/terms.md"));
assert.equal(compileGlob("a.b").test("axb"), false);
const config = { url: "https://facereader.witbacon.com", algolia: { files_to_exclude: ["docs/_pages/**"] } };
const record = { url: config.url + "/article/", path: "docs/_posts/article.md", title: "文章", description: "摘要", content: "😀中文 content ".repeat(3000), type: "post", language: "zh", date: "2026-10-27T00:00:00Z", date_ts: 1793059200, categories: [], tags: [] };
const prepared = prepareRecords([record], config);
assert.ok(Buffer.byteLength(JSON.stringify(prepared[0])) <= 9000);
assert.ok(prepared[0].content.length);
assert.ok(!/[\uD800-\uDBFF]$/.test(prepared[0].content));
assert.equal(prepared[0].objectID, prepareRecords([record], config)[0].objectID);
assert.throws(() => prepareRecords([], config), /empty/);
assert.throws(() => prepareRecords([record], {}), /configuration/);
assert.throws(() => prepareRecords([record, record], config), /Duplicate/);
assert.throws(() => prepareRecords([{ ...record, url: "https://other.example/article/" }], config), /URL/);
assert.throws(() => prepareRecords([{ ...record, path: "docs/_pages/terms.md" }], config), /all records/);
assert.throws(() => prepareRecords([{ ...record, content: null }], config), /fields/);
assert.throws(() => prepareRecords([{ ...record, categories: "bad" }], config), /metadata/);
assert.throws(() => prepareRecords([{ ...record, title: "x".repeat(10000) }], config), /budget/);
console.log("Offline search preflight: recursive glob exclusions, invalid/empty input, duplicate URLs and UTF-8 record budget passed.");
