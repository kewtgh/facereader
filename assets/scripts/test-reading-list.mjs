import assert from "node:assert/strict";
import { readSaved, validPath, readingListLimit } from "../js/reading-list-data.mjs";
for (const value of ["//evil.example/", "/\\evil", "/%2fevil", "/\n/evil", "javascript:alert(1)", "/x?q=1"]) assert.equal(validPath(value), false, value);
assert.equal(validPath("/人格成长/领导力/"), true);
assert.deepEqual(readSaved('{"not":"an array"}'), []);
assert.deepEqual(readSaved("broken"), []);
assert.deepEqual(readSaved(JSON.stringify(["/one/", "/one/", "//evil.example/", 1, "/two/"])), ["/one/", "/two/"]);
assert.equal(readSaved(JSON.stringify(Array.from({ length: readingListLimit + 5 }, (_, i) => `/post/${i}/`))).length, readingListLimit);
console.log("Reading-list storage, malformed values, duplicate removal and URL boundaries passed.");
import { serializeReadingBackup, mergeReadingBackup, readingListBackupBytes } from "../js/reading-list-data.mjs";
const available = new Set(["/one/", "/two/"]);
const backup = serializeReadingBackup(["/two/", "/two/", "/missing/"]);
assert.deepEqual(mergeReadingBackup(backup, ["/one/"], available), { urls: ["/one/", "/two/"], added: 1, skipped: 1 });
assert.deepEqual(mergeReadingBackup(serializeReadingBackup(["/one/"]), ["/one/"], available).urls, ["/one/"]);
for (const raw of ["invalid", "[]", '{"format":"facereader.readingList","version":2,"urls":[]}', '{"format":"facereader.readingList","version":1,"urls":["https://bad.example/"]}']) assert.throws(() => mergeReadingBackup(raw, [], available), /invalid/);
assert.throws(() => mergeReadingBackup(" ".repeat(readingListBackupBytes + 1), [], available), /size/);
assert.throws(() => mergeReadingBackup(serializeReadingBackup(["/two/"]), Array.from({ length: 100 }, (_, i) => `/saved/${i}/`), available), /limit/);
console.log("Local reading backups: roundtrip, additive merge, unavailable URLs, invalid files, size and capacity limits passed.");
